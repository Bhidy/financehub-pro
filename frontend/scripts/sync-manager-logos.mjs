#!/usr/bin/env node
/**
 * FUND MANAGER LOGOS — mirror + quality gate.
 *
 * lib/manager-logos.json is the source of truth (owner-approved 2026-08-15).
 * The static homepage cannot import JSON, so this mirrors it into
 * public/assets/manager-logos.js, and validates every file:
 *
 *   · the file must exist
 *   · a RASTER logo must be >= MIN_RASTER_WIDTH px wide — the wall renders a
 *     52px mark, so anything under ~104px is visibly soft on a retina screen.
 *     Naeem (79px) was rejected for exactly this reason and left as a monogram.
 *   · SVGs are exempt: they scale.
 *
 *     node scripts/sync-manager-logos.mjs
 *
 * A manager with no entry renders a name monogram. That is deliberate: showing
 * the WRONG institution's logo on a financial site is far worse than showing
 * initials, so a logo only ever appears when it was verified from that
 * company's own website.
 */
import { readFile, writeFile, access } from "node:fs/promises";
import { constants } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { imageSize } from "./sync-learn-image-sizes.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(root, "lib/manager-logos.json");
const MIRROR = path.join(root, "public/assets/manager-logos.js");

export const MIN_RASTER_WIDTH = 104;

export async function validate() {
  const { logos } = JSON.parse(await readFile(SRC, "utf8"));
  const problems = [];
  for (const [key, entry] of Object.entries(logos)) {
    const abs = path.join(root, "public", entry.file);
    try {
      await access(abs, constants.F_OK);
    } catch {
      problems.push(`${key}: missing file ${entry.file}`);
      continue;
    }
    if (entry.file.endsWith(".svg")) continue; // vector — scales cleanly
    const size = await imageSize(abs);
    if (!size) {
      problems.push(`${key}: could not read dimensions of ${entry.file}`);
    } else if (size.w < MIN_RASTER_WIDTH) {
      problems.push(`${key}: ${entry.file} is ${size.w}px wide (min ${MIN_RASTER_WIDTH})`);
    }
  }
  return { logos, problems };
}

async function run() {
  const { logos, problems } = await validate();
  if (problems.length) {
    console.error("FAIL: manager logo problems:\n" + problems.map((p) => `  · ${p}`).join("\n"));
    process.exit(1);
  }
  const js = `/**
 * Generated by scripts/sync-manager-logos.mjs — do not edit.
 * Source of truth: lib/manager-logos.json
 */
window.STARTA_MANAGER_LOGOS = ${JSON.stringify(
    Object.fromEntries(Object.entries(logos).map(([k, v]) => [k, v.file])),
    null,
    4
  )};
`;
  await writeFile(MIRROR, js, "utf8");
  console.log(`manager logos: ${Object.keys(logos).length} verified and mirrored`);
  for (const [k, v] of Object.entries(logos)) console.log(`  ${k} -> ${v.file}  (${v.source})`);
}

if (import.meta.url === `file://${process.argv[1]}`) await run();
