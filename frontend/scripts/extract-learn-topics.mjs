/**
 * Extracts the Learn academy content from public/data/learn-topics.js
 * (the browser-global file the static learn pages load) into
 * content/learn-topics.generated.ts (a committed TS module — the repo
 * .gitignore blanket-ignores *.json) so server components / sitemaps import it.
 *
 * public/data/learn-topics.js remains the AUTHORING source until the Learn
 * hub itself migrates to the App Router; run this script after editing it:
 *   node scripts/extract-learn-topics.mjs
 */
import { createRequire } from 'module';
import { writeFileSync, mkdirSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);

globalThis.window = {};
require(join(here, '../public/data/learn-topics.js'));
const topics = globalThis.window.STARTA_LEARN_TOPICS;

if (!Array.isArray(topics) || topics.length === 0) {
    console.error('FATAL: STARTA_LEARN_TOPICS not found or empty');
    process.exit(1);
}
mkdirSync(join(here, '../content'), { recursive: true });
const out = join(here, '../content/learn-topics.generated.ts');
const banner = '/* AUTO-GENERATED by scripts/extract-learn-topics.mjs — do not edit by hand.\n' +
    ' * Source of truth: public/data/learn-topics.js */\n';
writeFileSync(out, `${banner}const learnTopics = ${JSON.stringify(topics, null, 1)};\n\nexport default learnTopics;\n`);
console.log(`Wrote ${topics.length} topics -> ${out}`);
