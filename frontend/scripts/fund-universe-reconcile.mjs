#!/usr/bin/env node
/**
 * FUND UNIVERSE RECONCILIATION — Starta's fund coverage against the regulator's count.
 *
 *   node scripts/fund-universe-reconcile.mjs            # live: read the public API + sitemap, write content/fund-universe-reconciliation.json
 *   node scripts/fund-universe-reconcile.mjs --check    # exit 1 if the committed file is older than 35 days
 *
 * WHY THIS EXISTS (audit 2026-09-05). The directory said "207 Egyptian mutual
 * funds"; the FRA's Q2-2026 report counts 224 funds by issuance. Neither
 * number is wrong, but a site that claims to cover "all Egyptian funds" owes
 * the reader the reconciliation: which of the regulator's vehicle types it
 * prices, how many of its own pages are dormant, and how large the residual
 * is that it cannot yet explain fund-by-fund (the FRA publishes per-type
 * counts; a per-fund register is not public). Every statement on the hub
 * and the methodology page about coverage is read from the file this writes.
 *
 * Inputs: the platform's own list API (the marketplace universe), the funds
 * sitemap (every fund page, dormant included) and scripts/fixtures/
 * fra-fund-universe.json (the FRA table, transcribed each quarter).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(root, 'content/fund-universe-reconciliation.json');
const SITE = process.env.SITE_URL || 'https://startamarkets.com';
const args = process.argv.slice(2);

if (args.includes('--check')) {
    if (!existsSync(OUT)) { console.error('[reconcile] missing content/fund-universe-reconciliation.json'); process.exit(1); }
    const cur = JSON.parse(readFileSync(OUT, 'utf8'));
    const ageDays = (Date.now() - Date.parse(cur.as_of)) / 86_400_000;
    if (ageDays > 35) { console.error(`[reconcile] reconciliation is ${Math.floor(ageDays)} days old — rerun: node scripts/fund-universe-reconcile.mjs`); process.exit(1); }
    console.log(`[reconcile] OK — ${Math.floor(ageDays)} days old`);
    process.exit(0);
}

const fra = JSON.parse(readFileSync(path.join(root, 'scripts/fixtures/fra-fund-universe.json'), 'utf8'));
const ua = { 'user-agent': 'starta fund-universe-reconcile/1.0' };

const funds = await (await fetch(`${SITE}/api/v1/funds?market=EGX`, { headers: ua })).json();
if (!Array.isArray(funds) || funds.length < 100) throw new Error(`list API returned ${Array.isArray(funds) ? funds.length : typeof funds} rows — refusing to write`);
const sitemap = await (await fetch(`${SITE}/sitemaps/funds.xml`, { headers: ua })).text();
const pageIds = new Set([...sitemap.matchAll(/startamarkets\.com\/Funds\/(\d+)-[^/<]*<\/loc>/g)].map((m) => m[1]));
const currentIds = new Set(funds.map((f) => String(f.fund_id)));
const dormant = [...pageIds].filter((id) => !currentIds.has(id)).sort((a, b) => Number(a) - Number(b));

// Starta by category: the same classifier the pages use (disclosed type, else
// registered name). The API already resolved fund_type through it.
const cat = (f) => {
    const t = String(f.fund_type || '').toLowerCase();
    if (f.is_shariah === true || f.is_shariah === 'true') return 'shariah';
    if (/money_market/.test(t)) return 'money-market';
    if (/fixed_income|bond/.test(t)) return 'fixed-income';
    if (/equity/.test(t)) return 'equity';
    if (/balanced|mixed/.test(t)) return 'balanced';
    if (/gold|commodit/.test(t)) return 'gold';
    return 'unclassified';
};
const byCategory = {};
for (const f of funds) byCategory[cat(f)] = (byCategory[cat(f)] || 0) + 1;
const byCurrency = {};
for (const f of funds) byCurrency[f.currency || 'EGP'] = (byCurrency[f.currency || 'EGP'] || 0) + 1;

// FRA by Starta category (only types Starta prices), and the out-of-scope vehicles.
const fraByCategory = {};
let fraOutOfScope = 0;
const outOfScopeTypes = [];
for (const t of fra.by_type) {
    if (!t.starta_scope) { fraOutOfScope += t.count; outOfScopeTypes.push({ type_en: t.type_en, type_ar: t.type_ar, count: t.count }); continue; }
    const k = t.starta_category ?? 'other';
    fraByCategory[k] = (fraByCategory[k] || 0) + t.count;
}
const fraInScope = fra.total_funds_by_issuance - fraOutOfScope;
const residual = fraInScope - funds.length - dormant.length;

const out = {
    _comment: 'GENERATED by scripts/fund-universe-reconcile.mjs — do not edit by hand. Counts are by issuance on both sides. The residual is the part of the regulator\'s in-scope count that cannot be matched fund-by-fund because the FRA publishes type totals, not a per-fund register.',
    as_of: new Date().toISOString().slice(0, 10),
    fra: {
        source_url: fra.source_url,
        report_date: fra.report_date,
        period_end: fra.period_end,
        total_by_issuance: fra.total_funds_by_issuance,
        in_scope_for_starta: fraInScope,
        out_of_scope: { count: fraOutOfScope, types: outOfScopeTypes },
        by_starta_category: fraByCategory,
    },
    starta: {
        current_priced_funds: funds.length,
        dormant_funds_with_pages: dormant.length,
        dormant_fund_ids: dormant,
        total_fund_pages: pageIds.size,
        by_category: byCategory,
        by_currency: byCurrency,
        universe_rule: 'a NAV published within 180 days and at least 2 NAV points (lib/fund-stats.ts: DORMANT_DAYS, MIN_NAV_POINTS)',
    },
    delta: {
        fra_in_scope_minus_starta_pages: residual,
        explanation: [
            `${fraOutOfScope} FRA issuances are vehicle types Starta does not price (private-equity, real-estate, fund-of-funds, ETF) — they publish no public unit price to track.`,
            `${dormant.length} Starta fund pages are dormant (no NAV for 180+ days: matured target-date funds, frozen sources) and are excluded from the current universe but kept as history.`,
            `${residual} in-scope FRA issuances are not yet individually reconcilable: the FRA reports type totals, and recent launches (15 new funds in Q2 2026 per the FRA) publish their first NAVs with a lag. New funds enter the directory automatically once a manager publishes at least two NAVs.`,
        ],
    },
    statement: {
        en: `Starta prices ${funds.length} publicly offered Egyptian mutual funds with a current NAV (plus ${dormant.length} dormant funds kept as history). The Financial Regulatory Authority counted ${fra.total_funds_by_issuance} funds by issuance at end-June 2026, of which ${fraOutOfScope} are private-equity, real-estate, fund-of-funds or ETF vehicles with no public unit price; the remaining gap (${residual}) is recent launches and type-level differences the regulator's report does not itemise.`,
        ar: `تنشر ستارتا أسعار ${funds.length} صندوق استثمار مصري مطروحًا للجمهور بصافي قيمة أصول حديث (إضافةً إلى ${dormant.length} صناديق متوقفة تُحفَظ كسجل). وأحصت الهيئة العامة للرقابة المالية ${fra.total_funds_by_issuance} صندوقًا بإصداراتها في نهاية يونيو 2026، منها ${fraOutOfScope} صناديق ملكية خاصة وعقارية وقابضة ومؤشرات متداولة لا تُنشر أسعار وثائقها للجمهور؛ والفارق المتبقي (${residual}) إصدارات حديثة وفروق تصنيف لا يفصّلها تقرير الهيئة.`,
    },
};
writeFileSync(OUT, JSON.stringify(out, null, 1) + '\n');
console.log(`[reconcile] wrote ${OUT}`);
console.log(`[reconcile] FRA ${fra.total_funds_by_issuance} (in scope ${fraInScope}) vs Starta ${funds.length} current + ${dormant.length} dormant = ${pageIds.size} pages; residual ${residual}`);
console.log('[reconcile] Starta by category:', byCategory, '| FRA by category:', fraByCategory);
